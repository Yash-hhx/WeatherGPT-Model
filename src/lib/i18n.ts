export function translateCard(
  hazardId: HazardId,
  lang: LangCode,
  label: string,
  action?: string,
  details?: string,
  occupation?: Occupation,
  phase?: DisasterPhase,
): CardText | null {
  if (lang === "en") return null;

  // 1. Direct match in hazard bundle
  const bundleCard = TRANSLATIONS[hazardId]?.[lang]?.cards?.[label];
  if (bundleCard) {
    return bundleCard;
  }

  // 2. Direct match in universal tips translation library
  const tipCard = CARD_TIPS_TRANSLATIONS[label]?.[lang];
  if (tipCard) {
    return tipCard;
  }

  // 3. Match across any hazard bundle with matching card label
  for (const hId of Object.keys(TRANSLATIONS) as HazardId[]) {
    const candidate = TRANSLATIONS[hId]?.[lang]?.cards?.[label];
    if (candidate) return candidate;
  }

  return null;
}

export function translateHeadline(hazardId: HazardId, lang: LangCode): string | null {
  if (lang === "en") return null;
  return TRANSLATIONS[hazardId]?.[lang]?.headline ?? null;
}

export function translateOccupation(occ: Occupation, lang: LangCode): string | null {
  if (lang === "en") return null;
  return OCCUPATION_TRANSLATIONS[occ]?.[lang] ?? null;
}

export function translatePhase(
  phase: DisasterPhase,
  lang: LangCode,
): { label: string; desc: string; iconLabel: string } | null {
  if (lang === "en") return null;
  return PHASE_TRANSLATIONS[phase]?.[lang] ?? null;
}
